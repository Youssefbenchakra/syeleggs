      function startProcessing() {
        const username = document.getElementById("username-field").value.trim();
        if (!username) {
          document.getElementById("username-error").classList.remove("hidden");
          return;
        }
        document.getElementById("username-error").classList.add("hidden");
        document.getElementById("success-username").innerText = username;
        showPanel("progress");

        let progress = 0;
        const bar = document.getElementById("progress-bar-fill");
        const pct = document.getElementById("progress-pct");

        const interval = setInterval(() => {
          progress += 1;
          bar.style.width = `${progress}%`;
          pct.innerText = `${progress}%`;

          if (progress === 25) activateStep(2);
          if (progress === 55) activateStep(3);
          if (progress === 85) activateStep(4);

          if (progress >= 100) {
            clearInterval(interval);
            setTimeout(() => {
              showPanel("success");
              startCountdown();
              triggerConfetti();
            }, 400);
          }
        }, 45);
      }

      function activateStep(num) {
        const row = document.getElementById(`step-row-${num}`);
        const icon = document.getElementById(`step-icon-${num}`);
        if (row && icon) {
          row.classList.remove("opacity-40", "border-transparent");
          row.classList.add(
            "bg-white/[0.03]",
            "border-white/[0.1]",
            "text-slate-200"
          );
          icon.innerHTML = `<span class="w-2 h-2 rounded-full bg-indigo-400 animate-ping"></span>`;
        }
      }

      function startCountdown() {
        let left = 300;
        const label = document.getElementById("countdown-timer");
        if (countdownInterval) clearInterval(countdownInterval);
        countdownInterval = setInterval(() => {
          left--;
          if (left <= 0) {
            clearInterval(countdownInterval);
            label.innerText = "00:00";
            return;
          }
          const m = Math.floor(left / 60);
          const s = left % 60;
          label.innerText = `0${m}:${s < 10 ? "0" : ""}${s}`;
        }, 1000);
      }

